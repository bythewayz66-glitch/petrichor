using System;
using System.IO;
using UnityEngine;

namespace PET.Benchmarks
{
    /// <summary>
    /// Runs the four scenarios in order and writes their summaries to disk.
    ///
    /// WHY A RUNNER AND NOT FOUR INDEPENDENT TESTS
    /// -------------------------------------------
    /// The scenarios share a solver instance and a tier name, and the checker
    /// reads a directory of summaries rather than a set of test results. Running
    /// them through one entry point means the tier is resolved once, the output
    /// directory is created once, and a scenario that throws cannot leave the
    /// directory in a half-written state that the checker would read as a
    /// partial pass.
    ///
    /// ORDER IS NOT ARBITRARY
    /// ----------------------
    /// A, B, C, then D. The three budget scenarios run first so their summaries
    /// exist even if the determinism check fails - a determinism failure is a
    /// HARD FAIL either way, but having the timings on disk makes the report
    /// more useful. D runs last because it is the only scenario that can fail
    /// without producing a number.
    /// </summary>
    public static class BenchmarkHarness
    {
        /// <summary>
        /// Where summaries are written. Relative to the working directory, which
        /// in a headless run is the project root. The directory is git-ignored
        /// except for the verdict files - raw samples are large, machine-specific
        /// and regenerated by every run, while the verdict is a project decision
        /// record.
        /// </summary>
        public const string OutputDirName = "BenchmarkResults";

        /// <summary>
        /// The tier under test, from the environment. Set by
        /// <c>Tools/run_bench.sh</c>; "unknown" when a developer runs the tests
        /// from the editor without it, which is a legitimate way to use the
        /// harness but produces a summary the checker will not accept as a
        /// verdict.
        /// </summary>
        public static string Tier =>
            Environment.GetEnvironmentVariable("PET_BENCH_TIER") ?? "unknown";

        public static string OutputDir =>
            Path.Combine(Directory.GetCurrentDirectory(), OutputDirName);

        /// <summary>
        /// Run all four scenarios. Returns the three budget results; the
        /// determinism scenario returns nothing because it has no budget.
        /// </summary>
        public static ScenarioResult[] RunAll(IWaterSolver solver)
        {
            Directory.CreateDirectory(OutputDir);

            string tier = Tier;
            Debug.Log($"[PET.Benchmarks] harness start - solver '{solver.Name}', tier '{tier}', " +
                      $"res {BenchmarkScenarios.TileRes}, {BenchmarkScenarios.TileCount} tiles, " +
                      $"dt {BenchmarkScenarios.Dt:R} s, output {OutputDir}");

            var results = new ScenarioResult[3];

            results[0] = StaticSoakScenario.Run(solver, tier);
            Write(results[0]);

            results[1] = StepFloodScenario.Run(solver, tier);
            Write(results[1]);

            results[2] = FastForwardScenario.Run(solver, tier);
            Write(results[2]);

            // Last, because it is the only scenario that can fail without
            // producing a number.
            CorrectnessScenario.Run(solver);

            Debug.Log("[PET.Benchmarks] harness complete - 3 summaries written, determinism OK.");
            return results;
        }

        /// <summary>
        /// Write one summary, and log the same numbers on a single PET_BENCH
        /// line so they also land in the NUnit results XML. The checker prefers
        /// the summary file and falls back to the XML, so both paths carry the
        /// same values.
        /// </summary>
        public static void Write(ScenarioResult result)
        {
            Directory.CreateDirectory(OutputDir);

            string json = result.ToJson();
            string path = Path.Combine(OutputDir, $"summary_{result.Scenario}.json");
            File.WriteAllText(path, json);

            Debug.Log($"PET_BENCH {json}");
            Debug.Log($"[PET.Benchmarks] wrote {path}");
        }
    }
}
